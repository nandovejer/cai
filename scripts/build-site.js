/**
 * CAI Site — Dist builder
 * Regenerates packages/site/dist assets from packages/site/src.
 *
 * Usage: node scripts/build-site.js (from the repo root)
 */

import { cpSync, existsSync, mkdirSync, rmSync, readFileSync, writeFileSync } from "fs";
import { dirname, relative, resolve } from "path";
import { fileURLToPath } from "url";
import * as esbuild from "esbuild";
import { inCaiLayer } from "./cai-layers.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const siteRoot = resolve(repoRoot, "packages/site");
const srcRoot = resolve(siteRoot, "src");
const distRoot = resolve(siteRoot, "dist");

// Start from a clean dist so removed sources never linger in the tarball
rmSync(distRoot, { recursive: true, force: true });
mkdirSync(distRoot, { recursive: true });

/**
 * Recursively inline the local @import graph of a CSS file.
 * src/index.css is the single source of truth for layer order.
 * Relative url()s (the image placeholders) are rebased from the imported
 * file to src/, which dist/site.css mirrors: dist/ keeps src/'s layout
 * for assets, so the same URL works from npm and from a CDN.
 */
const assetUrls = new Set();
function inlineCssImports(filePath, seen = new Set()) {
  if (seen.has(filePath)) return "";
  seen.add(filePath);
  const dir = dirname(filePath);
  return readFileSync(filePath, "utf-8")
    .replace(/(?<!@import\s*)url\(\s*(["']?)(?![a-z]+:|\/|#)([^"')]+)\1\s*\)/g, (_, quote, relPath) => {
      const rebased = relative(srcRoot, resolve(dir, relPath)).split("\\").join("/");
      assetUrls.add(rebased);
      return `url(${quote}${rebased}${quote})`;
    })
    .replace(
      /@import\s+url\(\s*["']?(\.[^"')]+)["']?\s*\)\s*;/g,
      (_, relPath) => inlineCssImports(resolve(dir, relPath), seen),
    );
}

// In the cai.site layer, after cai.utilities, as unlayered site CSS
// won over core before; now a consumer's `app` layer wins over it
const siteCss = inCaiLayer("site", inlineCssImports(resolve(srcRoot, "index.css")));
// JS modules: site.js (the entry, which wires them) and one per concern
const jsModules = ["site.js", "search.js"];

// Image placeholders: the rasters are generated by scripts/build-placeholders.js
// and committed, so this build only copies them (no ImageMagick needed here)
cpSync(resolve(srcRoot, "placeholders"), resolve(distRoot, "placeholders"), { recursive: true });
const missing = [...assetUrls].filter((url) => !existsSync(resolve(distRoot, url)));
if (missing.length) {
  console.error(`✗ site.css points at files that do not exist:\n  ${missing.join("\n  ")}`);
  process.exit(1);
}
console.log(`✓ Site placeholders copied → ${resolve(distRoot, "placeholders")}`);

writeFileSync(resolve(distRoot, "site.css"), siteCss, "utf-8");
console.log(`✓ Site CSS built → ${resolve(distRoot, "site.css")}`);
// Unminified modules are copied as they are: they import each other by relative path
for (const file of jsModules) cpSync(resolve(srcRoot, file), resolve(distRoot, file));
console.log(`✓ Site JS synced → ${jsModules.join(", ")}`);

const { code: minCss } = await esbuild.transform(siteCss, { loader: "css", minify: true });
writeFileSync(resolve(distRoot, "site.min.css"), minCss, "utf-8");
console.log(`✓ Site CSS minified → ${resolve(distRoot, "site.min.css")}`);

// site.min.js is one file with search.js inside, so its budget measures
// everything a <script> of it loads; search.min.js is the module on its own
for (const file of jsModules) {
  await esbuild.build({
    entryPoints: [resolve(srcRoot, file)],
    outfile: resolve(distRoot, file.replace(/\.js$/, ".min.js")),
    bundle: true,
    // Bundle our own relative files only: a bare import (another package,
    // a third-party module) stays an import, which check-size then rejects,
    // instead of being inlined silently into a published file (RL-1;
    // security.md, phase 4 review, answer 5a)
    packages: "external",
    // The sideEffects field of package.json lists dist/ only (src/ is not
    // published), so esbuild would read src/search.js as pure and drop the
    // import that defines <cai-site-search>, leaving site.min.js empty
    ignoreAnnotations: true,
    format: "esm",
    minify: true,
    target: "es2022",
    legalComments: "none",
    logLevel: "warning",
  });
}
console.log(`✓ Site JS bundled and minified → ${jsModules.map((f) => f.replace(/\.js$/, ".min.js")).join(", ")}`);